#!/usr/bin/env python3
"""Generate rtl/ad_rx_setup_uc.sv: ad_rx_setup's micro-program ROM.

Instruction = {op[3:0], d[7:0], a[6:0], b[6:0]} (26 bits).  Register map:
  0-11  clip xyzw of v0..v2      12-20 weights (12 + 3v + k)
  21-26 VIEWPORT xs ys xo yo zs zo   27 1.0
  28-30 1/w of v0..v2            31-39 window x y z of v0..v2
  40-46 DX1 DY1 DX2 DY2 DF OX OY (written by ad_rx_edge)
  47 1/DF   48-51 temporaries   52-63 planes z, 1/w, b0/w, b1/w (A, B, C)
  64-66 b0/w per vertex   67-69 b1/w per vertex   70 1/POINT_SIZE  71 temp
  76-79 viewport rectangle  120 DBC 121 DBS 122 DBCL 123 0.5 124 0
  125 r of D16/D24  126 POINT_SIZE  127 LINE_WIDTH   (120-127 read only)
"""
import pathlib

OPS = dict(END=0, ADD=1, SUB=2, MUL=3, DIV=4, INT=5, OUT=6, JMP=7, MOV=8,
           ABS=9, MAX=10, ULP=11, BCL=12, BRA=13, ZR=14, NOP=15)
# BRA conditions
C_PNT, C_LIN, C_NOBIAS, C_NOT32, C_NORECT, C_RAW, C_EMPTY = range(7)

prog, labels = [], {}


def L(name):
    labels[name] = len(prog)


def I(op, d=0, a=0, b=0):
    prog.append((op, d, a, b))


def vtx(v):
    I("DIV", 28 + v, 27, 3 + 4 * v)                 # 1/w
    for c in range(3):
        I("MUL", 48 + c, c + 4 * v, 28 + v)          # x/w, y/w, z/w
    I("MUL", 48, 21, 48); I("ADD", 31 + 3 * v, 48, 23)   # xs * xd + xo
    I("MUL", 49, 22, 49); I("ADD", 32 + 3 * v, 49, 24)
    I("MUL", 50, 25, 50); I("ADD", 33 + 3 * v, 50, 26)
    I("MUL", 64 + v, 12 + 3 * v, 28 + v)             # b0/w at the vertex
    I("MUL", 67 + v, 13 + 3 * v, 28 + v)             # b1/w


def rect(tag):
    I("BRA", f"NR{tag}", C_NORECT)
    I("ABS", 48, 21); I("SUB", 76, 23, 48); I("ADD", 77, 23, 48)
    I("ABS", 49, 22); I("SUB", 78, 24, 49); I("ADD", 79, 24, 49)
    L(f"NR{tag}")


def plane(fa, fb, fc, p):
    A, B, C = p, p + 1, p + 2
    I("SUB", 48, fb, fa); I("SUB", 49, fc, fa)       # d1, d2
    I("MUL", 50, 48, 43); I("MUL", 51, 49, 41); I("SUB", 50, 50, 51); I("MUL", A, 50, 47)
    I("MUL", 50, 49, 40); I("MUL", 51, 48, 42); I("SUB", 50, 50, 51); I("MUL", B, 50, 47)
    I("MUL", 50, A, 45); I("MUL", 51, B, 46); I("ADD", 50, 50, 51); I("ADD", C, fa, 50)


def planes():
    I("DIV", 47, 27, 44)
    plane(33, 36, 39, 52)       # z
    plane(28, 29, 30, 55)       # 1/w
    plane(64, 65, 66, 58)       # b0/w
    plane(67, 68, 69, 61)       # b1/w


def bias(tag):
    I("BRA", f"NB{tag}", C_NOBIAS)
    I("ABS", 48, 52); I("ABS", 49, 53); I("MAX", 48, 48, 49); I("MUL", 48, 48, 121)
    I("BRA", f"LR{tag}", C_NOT32)
    I("ABS", 49, 33); I("ABS", 50, 36); I("MAX", 49, 49, 50)
    I("ABS", 50, 39); I("MAX", 49, 49, 50); I("ULP", 49, 49); I("MUL", 49, 49, 120)
    I("JMP", f"LS{tag}")
    L(f"LR{tag}"); I("MUL", 49, 125, 120)
    L(f"LS{tag}"); I("ADD", 48, 48, 49); I("BCL", 48, 48, 122); I("ADD", 54, 54, 48)
    L(f"NB{tag}")


# ---- triangle -------------------------------------------------------------
L("TRI")
for v in range(3):
    vtx(v)
# ---- shared by every kind: rectangle, INT, planes, bias, outputs ----------
L("TCOM")
rect("T")
I("INT", 0)
I("BRA", "PPL", C_PNT)
I("BRA", "FIN", C_EMPTY)
planes()
bias("T")                       # C_NOBIAS also covers "not a triangle"
L("FIN"); I("ZR")
I("BRA", "LT", C_LIN)
I("BRA", "LT", C_PNT)
I("END")
L("LT"); I("OUT"); I("INT", 1); I("END")   # lines, points: second sub-triangle

# ---- DRAW_RAW: screen space, w = 1 ----------------------------------------
L("RAW")
for v in range(3):
    I("MOV", 31 + 3 * v, 4 * v); I("MOV", 32 + 3 * v, 1 + 4 * v); I("MOV", 33 + 3 * v, 2 + 4 * v)
    I("MOV", 28 + v, 27); I("MOV", 64 + v, 12 + 3 * v); I("MOV", 67 + v, 13 + 3 * v)
I("JMP", "TCOM")

# ---- line: planes from (a, b, c), c = a + one pixel along the minor axis ---
L("LIN")
vtx(0); vtx(1)
I("MOV", 39, 33); I("MOV", 30, 28); I("MOV", 66, 64); I("MOV", 69, 67)
I("JMP", "TCOM")

# ---- point -------------------------------------------------------------------
L("PNT")
vtx(0)
I("JMP", "TCOM")
L("PPL")                                            # PointCoord planes
I("DIV", 70, 27, 126)                               # 1 / POINT_SIZE
I("MOV", 52, 124); I("MOV", 53, 124); I("MOV", 54, 33)
I("MOV", 55, 124); I("MOV", 56, 124); I("MOV", 57, 27)
I("MOV", 58, 70);  I("MOV", 59, 124); I("MUL", 71, 45, 70); I("ADD", 60, 71, 123)
I("MOV", 61, 124); I("MOV", 62, 70);  I("MUL", 71, 46, 70); I("ADD", 63, 71, 123)
I("JMP", "FIN")

assert len(prog) <= 256
words = []
for op, d, a, b in prog:
    if isinstance(d, str):
        d = labels[d]
    words.append((OPS[op] << 22) | ((d & 0xFF) << 14) | ((a & 0x7F) << 7) | (b & 0x7F))

root = pathlib.Path(__file__).resolve().parent.parent
lines = [
    "// ============================================================================",
    "// ad_rx_setup_uc -- ad_rx_setup's micro-program ROM.",
    "// GENERATED by tools/gen_setup_uc.py -- edit the generator, not this file.",
    f"// {len(prog)} micro-instructions {{op[3:0], d[7:0], a[6:0], b[6:0]}}.",
    "// ============================================================================",
    "module ad_rx_setup_uc (",
    "  input  logic [7:0]  pc,",
    "  output logic [25:0] ins,",
    "  output logic [7:0]  e_tri,",
    "  output logic [7:0]  e_raw,",
    "  output logic [7:0]  e_lin,",
    "  output logic [7:0]  e_pnt",
    ");",
    f"  assign e_tri = 8'd{labels['TRI']};",
    f"  assign e_raw = 8'd{labels['RAW']};",
    f"  assign e_lin = 8'd{labels['LIN']};",
    f"  assign e_pnt = 8'd{labels['PNT']};",
    "  always_comb begin",
    "    case (pc)",
]
for i, w in enumerate(words):
    op, d, a, b = prog[i]
    lines.append(f"      8'd{i}: ins = 26'h{w:07x};   // {op} {d} {a} {b}")
lines += ["      default: ins = 26'h0;   // END", "    endcase", "  end", "endmodule", ""]
(root / "rtl" / "ad_rx_setup_uc.sv").write_text("\n".join(lines))
print(f"{len(prog)} micro-instructions; entries {labels['TRI']} {labels['RAW']} {labels['LIN']} {labels['PNT']}")
