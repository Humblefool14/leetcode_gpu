#!/usr/bin/env python3
"""Run the ad_rx formal proofs with SymbiYosys (prove = BMC base + k-induction,
cover = reachability).  Writes fpv/<module>.sby, runs each, prints a table.

    python3 fpv/run_fpv.py            # all modules
    python3 fpv/run_fpv.py ad_rx_fdiv # one module

Works with `sby` or `yowasp-sby`.  Assertions are procedural (immediate
assert/assume/cover inside `ifdef FORMAL), which open-source Yosys and
JasperGold both read.
"""
import pathlib, shutil, subprocess, sys, time

ROOT = pathlib.Path(__file__).resolve().parent.parent
RTL = ROOT / "rtl"

# module: (extra rtl files, prove depth, cover depth, has_cover, chparams)
JOBS = {
    "ad_rx_fadd":   ([], 1, 1, False, {}),
    "ad_rx_fmul":   ([], 1, 1, False, {}),
    "ad_rx_fdiv":   ([], 4, 34, True, {}),
    "ad_rx_i2f":    ([], 1, 1, False, {}),
    "ad_rx_f2fix":  ([], 1, 1, False, {}),
    "ad_rx_order":  ([], 8, 12, True, {}),
    "ad_rx_cov":    ([], 4, 6, True, {}),
    "ad_rx_coarse": ([], 3, 24, True, {"EW": 32, "CW": 8}),
    "ad_rx_hiz":    ([], 4, 40, True, {"AW": 3, "GW": 2, "ZW": 3}),
    "ad_rx_edge":   (["ad_rx_f2fix.sv", "ad_rx_i2f.sv"], 4, 36, False, {}),
    "ad_rx_scan":   (["ad_rx_coarse.sv", "ad_rx_cov.sv", "ad_rx_hiz.sv",
                      "ad_rx_i2f.sv", "ad_rx_fadd.sv", "ad_rx_fmul.sv"], 3, 30, True,
                     {"HZ_EN": 0}),
    "ad_rx_cpoly":  (["ad_rx_fadd.sv", "ad_rx_fmul.sv", "ad_rx_fdiv.sv"], 4, 40, False, {}),
    "ad_rx_clip":   (["ad_rx_cpoly.sv", "ad_rx_fadd.sv", "ad_rx_fmul.sv",
                      "ad_rx_fdiv.sv"], 4, 24, False, {}),
    "ad_rx_bary_lane": (["ad_rx_fadd.sv", "ad_rx_fmul.sv", "ad_rx_fdiv.sv"], 4, 54, False, {}),
    "ad_rx_bary":   (["ad_rx_bary_lane.sv", "ad_rx_fadd.sv", "ad_rx_fmul.sv", "ad_rx_fdiv.sv",
                      "ad_rx_i2f.sv"], 4, 56, False, {}),
    "ad_rx_frag":   (["ad_rx_bary.sv", "ad_rx_bary_lane.sv", "ad_rx_fadd.sv", "ad_rx_fmul.sv",
                      "ad_rx_fdiv.sv", "ad_rx_i2f.sv"], 4, 40, False, {}),
    "ad_rx_setup":  (["ad_rx_setup_uc.sv", "ad_rx_edge.sv", "ad_rx_f2fix.sv", "ad_rx_i2f.sv",
                      "ad_rx_fadd.sv", "ad_rx_fmul.sv", "ad_rx_fdiv.sv"], 4, 40, False, {}),
}

SBY = shutil.which("sby") or shutil.which("yowasp-sby")


# bounded model checking of the multiplier-heavy properties (-DFPV_BMC)
BMC = {"ad_rx_coarse": 16, "ad_rx_scan": 14}

# submodules replaced by cut points (free outputs) in the parent's proof:
# their own proofs stand alone; the parent's properties are about control
CUT = {
    "ad_rx_edge":  ["ad_rx_f2fix", "ad_rx_i2f"],
    "ad_rx_scan":  ["ad_rx_fadd", "ad_rx_fmul", "ad_rx_i2f"],
    "ad_rx_cpoly": ["ad_rx_fadd", "ad_rx_fmul", "ad_rx_fdiv"],
    "ad_rx_clip":  ["ad_rx_cpoly"],
    "ad_rx_bary":  ["ad_rx_fadd", "ad_rx_fmul", "ad_rx_fdiv", "ad_rx_i2f"],
    "ad_rx_frag":  ["ad_rx_bary", "ad_rx_i2f"],
    "ad_rx_setup": ["ad_rx_edge", "ad_rx_fadd", "ad_rx_fmul", "ad_rx_fdiv", "ad_rx_f2fix"],
}

# submodules whose assertions become assumptions in the parent's proof
# (assume-guarantee: each is proven on its own first)
A2A = {
    "ad_rx_scan":  ["ad_rx_coarse", "ad_rx_cov", "ad_rx_fdiv"],
    "ad_rx_edge":  [],
    "ad_rx_cpoly": ["ad_rx_fdiv"],
    "ad_rx_clip":  ["ad_rx_cpoly", "ad_rx_fdiv"],
    "ad_rx_bary":  ["ad_rx_bary_lane", "ad_rx_fdiv"],
    "ad_rx_frag":  ["ad_rx_bary", "ad_rx_bary_lane", "ad_rx_fdiv"],
    "ad_rx_setup": ["ad_rx_edge", "ad_rx_fdiv", "ad_rx_setup_uc"],
    "ad_rx":       ["ad_rx_clip", "ad_rx_cpoly", "ad_rx_setup", "ad_rx_edge", "ad_rx_scan",
                    "ad_rx_coarse", "ad_rx_cov", "ad_rx_frag", "ad_rx_bary",
                    "ad_rx_bary_lane", "ad_rx_order", "ad_rx_fdiv"],
}


def write_sby(top, extra, pdepth, cdepth, cover, params):
    files = ["ad_rx_pkg.sv"] + extra + [f"{top}.sv"]
    files = list(dict.fromkeys(files))
    tasks = "prv\ncvr\n" if cover else "prv\n"
    bmc = BMC.get(top)
    if bmc:
        tasks += "bmc\n"
    chp = "".join(f"chparam -set {k} {v} {top}\n" for k, v in params.items())
    subs = A2A.get(top, []) + ["ad_rx_fadd", "ad_rx_fmul", "ad_rx_i2f", "ad_rx_f2fix"]
    subs = [m for m in subs if m != top and f"{m}.sv" in extra]
    a2a = "".join(f"chformal -assert2assume a:src=*{m}.sv*\n" for m in subs)
    cut = "".join(f"cutpoint {m}\n" for m in CUT.get(top, []))
    cvo = f"cvr: mode cover\ncvr: depth {cdepth}\n" if cover else ""
    if bmc:
        cvo += f"bmc: mode bmc\nbmc: depth {bmc}\n"
    txt = f"""# generated by fpv/run_fpv.py
[tasks]
{tasks}
[options]
timeout 600
prv: mode prove
prv: depth {pdepth}
{cvo}
[engines]
smtbmc cvc5

[script]
{"bmc: read -formal -DFORMAL -DFPV_BMC " + " ".join(files) + chr(10) + "~bmc: " if bmc else ""}read -formal -DFORMAL {' '.join(files)}
{chp}prep -top {top}
{cut}flatten
{a2a}
[files]
""" + "".join(f"../rtl/{f}\n" for f in files)
    p = ROOT / "fpv" / f"{top}.sby"
    p.write_text(txt)
    return p


def run(top):
    extra, pd, cd, cov, par = JOBS[top]
    p = write_sby(top, extra, pd, cd, cov, par)
    t0 = time.time()
    r = subprocess.run([SBY, "-f", p.name], cwd=p.parent,
                       capture_output=True, text=True)
    dt = time.time() - t0
    res = {}
    for line in r.stdout.splitlines():
        if "DONE (" in line:
            task = line.split("[")[1].split("]")[0].split("_")[-1]
            res[task] = line.split("DONE (")[1].split(",")[0]
    if r.returncode != 0:
        tail = [l for l in r.stdout.splitlines()
                if "Assert" in l or "failed" in l or "ERROR" in l or "Unreached" in l]
        print("\n".join(tail[-12:]))
    return res, dt


if __name__ == "__main__":
    mods = sys.argv[1:] or list(JOBS)
    rows = []
    for m in mods:
        if not (RTL / f"{m}.sv").exists():
            continue
        res, dt = run(m)
        rows.append((m, res.get("prv", "-"), res.get("cvr", "-"), dt, res.get("bmc", "-")))
        print(f"{m:16s} prove={rows[-1][1]:6s} cover={rows[-1][2]:6s} bmc={rows[-1][4]:6s} {dt:7.1f}s", flush=True)
    bad = [r for r in rows if r[1] != "PASS" or r[2] not in ("PASS", "-") or r[4] not in ("PASS", "-")]
    print("ALL FPV PASS" if not bad else f"FPV FAILURES: {[b[0] for b in bad]}")
