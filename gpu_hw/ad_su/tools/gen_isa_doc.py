#!/usr/bin/env python3
# gen_isa_doc.py: writes docs/GSI1_ISA.md, the GSI1 encoding table, from
# tools/gsi1asm.py's instruction table T and decode() (the source of truth).
#   python3 -I tools/gen_isa_doc.py [-o docs/GSI1_ISA.md]
