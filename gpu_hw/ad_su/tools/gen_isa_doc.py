import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gsi1asm as A  # noqa: E402

UNITS = ["NONE", "ALU", "FPU", "PK", "XU", "DIV", "LSU", "LDS", "CBANK", "TEX", "EXP", "LDA",
         "LANE", "EXEC", "CTL", "RQ"]
CLS = "afmtx"
OPCN = {v: k for k, v in A.OPC.items()}
OPS = {"d": "rd", "1": "rs1", "2": "rs2", "3": "rs3", "i": "imm", "m": "imm(rs1)",
       "a": "(rs1)", "l": "label", "t": "slot", "x": "target", "w": "cm, ct, cx"}

HEAD = """# GSI1 instruction set: encoding table

Generated by `tools/gen_isa_doc.py` from the instruction table `T` and `decode()` of
`tools/gsi1asm.py` (the original GSI1 assembler, the source of truth); do not edit by hand.
The design's own tables (design §3.3 formats, §3.4 opcode table) were not available here: this
document is DERIVED from the assembler and the RTL decoder (`rtl/su/ad_su_dec*.v`) matches it
bit for bit (`sim/tb/ad_su_dec_tb.v`).  Unit/op/class names are those of
`rtl/include/ad_su_uop.vh`.

## 1. Instruction words

Every instruction is 64 bits: word0 (low, the RISC-V-like 32-bit encoding) then word1.

| Field | Bits | Meaning |
| --- | --- | --- |
| opcode | w0[6:0] | major opcode; w0[1:0] must be 11 |
| rd | w0[11:7] + w1[1:0] | 7-bit destination number (low 5 bits, high 2 bits) |
| funct3 | w0[14:12] | function / rounding mode `rm` |
| rs1 | w0[19:15] + w1[3:2] | 7-bit source number |
| rs2 | w0[24:20] + w1[5:4] | 7-bit source number (also selects fcvt/fsqrt/fround) |
| funct7 | w0[31:25] | function; R4 forms: fmt/funct2 = w0[26:25] |
| rs3 | w0[31:27] + w1[7:6] | 7-bit third source (R4 forms) |
| mod | w1[14:8] | float modifiers {sat, a3, n3, a2, n2, a1, n1} (n = negate, a = abs; abs first) |
| hsel | w1[16:15] | packed half select (01 low half, 10 high half, 11 rs2 halves swapped) |
| sub | w1[21:17] | sub-function (texture: sampler/texture slot sub[3:0]) |
| imm_hi | w1[31:22] | high immediate bits (I/S/B forms) |

Texture R forms reuse w1: sampler slot w1[9:6] (uop SAMP_SLOT), texel offsets du = w1[25:22],
dv = w1[29:26], dw = w1[13:10] (signed 4 bits; uop imm = du | dv << 4 | dw << 8).

### Operand numbers (7 bits)

| Number | Operand | Assembly |
| --- | --- | --- |
| 0-62 | GPR (must be < NREGS) | r0-r62 |
| 63 | rq (the SA queue; only with HAS_SA; as destination only for a class-a single destination) | rq |
| 64-95 | constant bank words c0-c31 (sources only) | c0-c31 |
| 96-127 | specials (sources only) | see below; `o<n>` gives any number |

Specials: %s.

### Immediates

| Format | uop IMM |
| --- | --- |
| I | sext(w0[31:20]) + (sext(w1[31:22]) << 12) |
| S | sext({w0[31:25], w0[11:7]}) + (sext(w1[31:22]) << 12) |
| B | sext({w0[31], w0[7], w0[30:25], w0[11:8]}) + (sext(w1[31:22]) << 12), an offset in instructions (pc-relative) |
| U (lui/movi) | {w0[31:12], w1[13:2]} (movi is lui's alias with the low 12 bits in w1) |
| R/R4 | 0, except texture R forms: the texel offsets |

U forms carry RS1-3, MOD, HSEL, SUB and RM = 0 in the uop; every other form carries all operand
fields as encoded (used or not) and RM = funct3.  A texture .3 form sets the uop's SUB[4].

### Rounding modes (`rm` operands rne/rtz/rdn/rup/rmm/dyn)

rm 0 RNE, 1 RTZ, 2 RDN, 3 RUP, 4 RMM, 7 dyn (= RNE, there is no CSR); 5 and 6 are ISA faults.
fround accepts rm 0-3 only.

## 2. ISA faults (uop = only the ILL bit, FAULT kind 8)

- w0[1:0] != 11; an opcode/funct3/funct7/rs2-field/sub/imm combination not in the table below
  (e.g. funct7 bit 6 on texture forms, atom sub[3:0] > 10, texture sub[4] = 1, texsz imm > 3).
- A source number 0-62 >= NREGS; source 63 (rq) without HAS_SA.
- A destination >= 64; rd 63 (rq) without HAS_SA, or for a class other than a, or with four
  destinations; rd + NDST > NREGS or > 63.
- PAIR (texture R forms): rs1+1 must stay in rs1's bank: rs1 <= min(NREGS, 63) - 2 for a GPR,
  not c31 / not 127.  .c or .3 forms: rs1+2 (the uop's rs3) likewise (rs1 <= LIM - 3, not c30-c31,
  not 126-127); .3 with .c: rs1+3 (rs1 <= LIM - 4, not c29-c31, not 125-127).
- Rows marked PK need PACKED, SG need SUBGROUP, SA need HAS_SA, MS4 need MS4.

## 3. Assembly syntax (tools/gsi1asm.py)

One instruction per line, `#` or `;` comments, `label:` prefixes.  Float sources take `-x`,
`|x|`, `-|x|`; `.sat` on a float mnemonic saturates (mod[6]); packed half select is a final
suffix `.hlo`, `.hhi` or `.hswap`; an optional last operand rne/rtz/rdn/rup/rmm/dyn sets rm
(default rne).  Branch operands are labels or instruction counts.  Atomics: `atom.<op> rd,
(rs1), rs2[, rs3]` on global memory, `atoms.<op>` on shared memory (sub[4]); ops %s
(sub[3:0] 0-10; cmpxchg reads rs3).  Texture: `texl rd, rs1, rs2, slot[, off(du, dv[, dw])]`;
`wait cm, ct, cx` (imm = cm | ct << 4 | cx << 8); `exp rs2, target` (number or colorK.r..a);
`.inst 0x<64 bits>` emits a raw word.  `movi rd, imm32` loads any 32-bit value.

## 4. The instruction table

Columns: mnemonic; format; major opcode; funct3 (`rm` = any rounding mode 0-4/7; `rm4` = 0-3);
the fixed funct7 / rs2 field / imm / sub; assembly operands; unit, op (hex), class; flags:
W rd written (NDST), S side effects, P PAIR, 3 reads rs3, and the parameter needed.

| Mnemonic | Fmt | Opcode | f3 | Fixed fields | Operands | Unit | Op | Cls | Flags |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
"""


def row(n, e):
    fixed = []
    if e["fmt"] in ("R",) and e["f7"] is not None:
        fixed.append("f7=0x%02x" % e["f7"])
    if e.get("shift"):
        fixed.append("imm[11:5]=0x%02x" % e["f7"])
    if e["fmt"] == "R4":
        fixed.append("fmt2=00" if e["opc"] != A.OPC["C0"] else "w0[26:25] any")
    if "rs2" in e:
        fixed.append("rs2=%d" % e["rs2"])
    if "immv" in e:
        fixed.append("imm=%d" % e["immv"])
    if "subv" in e:
        fixed.append("sub=%d" % e["subv"])
    if e.get("sub") == "atom":
        fixed.append("sub[3:0]=op, sub[4] shared")
    if e["unit"] == A.U_TEX:
        fixed.append("sub[4]=0")
    if e.get("movi"):
        fixed.append("alias of lui")
    ops = ", ".join(OPS[c] for c in e["ops"])
    if e.get("sub") == "atom":
        ops += "[, rs3]"
    if e["unit"] == A.U_TEX and e["fmt"] == "R":
        ops += "[, off(du, dv[, dw])]"
    if e.get("fp") and e["f3"] in ("rm", "rm4"):
        ops += "[, rm]"
    flags = []
    if "d" in e["ops"]:
        flags.append("W%d" % e.get("ndst", 1))
    if e.get("side"):
        flags.append("S")
    if e.get("pair"):
        flags.append("P")
    if "3" in e["ops"] or e.get("cmp") or e.get("three"):
        flags.append("3")
    if e.get("sub") == "atom":
        flags.append("3 (cmpxchg)")
    if e.get("three"):
        flags.append("sub[4]")
    for k, t in (("packed", "PK"), ("subgroup", "SG"), ("ms4", "MS4")):
        if e.get(k):
            flags.append(t)
    if e["unit"] == A.U_RQ:
        flags.append("SA")
    unit = UNITS[e["unit"]]
    if e.get("sub") == "atom":
        unit = "LSU / LDS (sub[4])"
    f3 = e["f3"] if isinstance(e["f3"], str) else ("-" if e["f3"] is None else str(e["f3"]))
    return "| `%s` | %s | %s 0x%02x | %s | %s | %s | %s | 0x%02x | %s | %s |" % (
        n, e["fmt"], OPCN[e["opc"]], e["opc"], f3, ", ".join(fixed) or "-", ops or "-", unit,
        e["op"], CLS[e["cls"]], " ".join(flags) or "-")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                                               "docs", "GSI1_ISA.md"))
    a = ap.parse_args()
    sp = ", ".join("%d %s" % (96 + i, s) for i, s in enumerate(A.SPECIAL))
    out = [HEAD % (sp, " ".join(A.ATOMS))]
    for n, e in A.T.items():
        out.append(row(n, e) + "\n")
    out.append("\n%d rows.  The decode vectors of `gsi1asm.py --dec-table` and "
               "`tools/gen_dec_vectors.py` check the RTL against this table.\n" % len(A.T))
    with open(a.o, "w") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main()
