"""gen_fblend_vectors.py -- test vectors (sim/vec/fblend_*.hex) and the generated
sRGB table RTL (rtl/rop/fblend/ad_fblend_srgb_lut.v, ad_fblend_srgb_enc.v) for
ad_rop_fblend.  Run from the repo root:  python3 -I tools/gen_fblend_vectors.py

Beat vector line (hex fields separated by '_', 1448 bits, MSB first):
  lanes(4) fmt(8) blend(24, [22:0] used) wm(4) const(128) src(512) dst(256) o_raw(256) o_keep(256)
"""
import math
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fblend_model as M          # noqa: E402
from admodel import b2f, f2b, rand_f32, unorm2f, QNAN   # noqa: E402

import numpy as np                # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VEC = os.path.join(ROOT, "sim", "vec")
RTL = os.path.join(ROOT, "rtl", "rop", "fblend")

rng = random.Random(0xFB1E)
nrng = np.random.default_rng(0xFB1E)


# ------------------------------------------------------------------ RTL tables
def emit_rtl():
    lines = ["// ad_fblend_srgb_lut -- sRGB code (0..255) to linear fp32: f = fp32 RNE of the exact",
             "// sRGB EOTF at c/255.  GENERATED by tools/gen_fblend_vectors.py (table from",
             "// tools/fblend_model.py SRGB_LUT); do not edit.  Combinational.",
             "module ad_fblend_srgb_lut (",
             "    input  wire [7:0]  c,",
             "    output reg  [31:0] f",
             ");",
             "    always @(*) begin",
             "        case (c)"]
    for c in range(256):
        lines.append("            8'd%d: f = 32'h%08X;" % (c, M.SRGB_LUT[c]))
    lines += ["            default: f = 32'h0000_0000;", "        endcase", "    end", "endmodule", ""]
    with open(os.path.join(RTL, "ad_fblend_srgb_lut.v"), "w") as fh:
        fh.write("\n".join(lines))

    lines = ["// ad_fblend_srgb_enc -- linear fp32 to sRGB code: c = number of k in 1..255 with",
             "// f >= T[k], T[k] = fp32 RNE of the exact sRGB EOTF at (k - 0.5)/255, found by an",
             "// unrolled 8-step binary search.  NaN and negatives (-0 included) give 0; f >= T[255]",
             "// (so f > 1 and +inf) gives 255.  For f >= 0 the fp32 order is the unsigned order of",
             "// the bit patterns, so the steps are integer compares.",
             "// GENERATED by tools/gen_fblend_vectors.py (tools/fblend_model.py SRGB_THR); do not edit.",
             "module ad_fblend_srgb_enc (",
             "    input  wire [31:0] f,",
             "    output wire [7:0]  c",
             ");",
             "    function [31:0] thr;",
             "        input [7:0] k;",
             "        begin",
             "            case (k)"]
    for k in range(1, 256):
        lines.append("                8'd%d: thr = 32'h%08X;" % (k, M.SRGB_THR[k]))
    lines += ["                default: thr = 32'h0000_0000;   // k = 0 is never looked up",
              "            endcase",
              "        end",
              "    endfunction",
              "    wire ok = !f[31] && !((f[30:23] == 8'hFF) && (f[22:0] != 23'd0));",
              "    wire [7:0] c7 = (f >= thr(8'h80)) ? 8'h80 : 8'h00;"]
    prev = "c7"
    for b in range(6, -1, -1):
        cur = "c%d" % b
        lines.append("    wire [7:0] %s = (f >= thr(%s | 8'h%02X)) ? (%s | 8'h%02X) : %s;"
                     % (cur, prev, 1 << b, prev, 1 << b, prev))
        prev = cur
    lines += ["    assign c = ok ? c0 : 8'd0;", "endmodule", ""]
    with open(os.path.join(RTL, "ad_fblend_srgb_enc.v"), "w") as fh:
        fh.write("\n".join(lines))


# ------------------------------------------------------------------ helpers
def hx(v, bits):
    return "%0*X" % ((bits + 3) // 4, v)


def rnd_unit():
    return f2b(float(np.float32(rng.random())))


def rnd_src_fixed():
    r = rng.random()
    if r < 0.06:
        return rng.choice([0, 0x80000000, 0x3F800000, 0x7F800000, 0xFF800000, QNAN, 0xFFC00001,
                           0x00000005, 0x3F800001, 0x40000000, 0xBF000000])
    if r < 0.8:
        return rnd_unit()
    return f2b(float(np.float32(rng.uniform(-0.5, 1.5))))


def rnd_src_float():
    r = rng.random()
    if r < 0.08:
        return rng.choice([0, 0x80000000, 0x3F800000, 0x7F800000, 0xFF800000, QNAN, 0x7F800123,
                           0x00000005, 0x80400000, 0x477FE000, 0x477FF000, 0x33800000, 0x33000000,
                           0x387FC000, 0x38800000, 0xC2C80000])
    if r < 0.45:
        return f2b(float(np.float32(rng.uniform(-2.0, 2.0))))
    if r < 0.85:   # anywhere in (and around) the fp16 range
        e = rng.randint(127 - 27, 127 + 17)
        return (rng.getrandbits(1) << 31) | (e << 23) | rng.getrandbits(23)
    return rand_f32(nrng)


def rnd_h():
    r = rng.random()
    if r < 0.5:
        return M.f2h(f2b(float(np.float32(rng.uniform(-1.5, 1.5)))))
    if r < 0.6:
        return rng.choice([0x0000, 0x8000, 0x3C00, 0x7C00, 0xFC00, 0x7E00, 0x7C01, 0xFE11, 0x0001,
                           0x83FF, 0x0400, 0x7BFF])
    return rng.getrandbits(16)


def rnd_dst(fmt):
    if fmt in (M.F_R16F, M.F_RG16F, M.F_RGBA16F):
        v = rnd_h() | (rnd_h() << 16) | (rnd_h() << 32) | (rnd_h() << 48)
        return v
    return rng.getrandbits(64)


def rnd_lanes():
    return 0xF if rng.random() < 0.6 else rng.getrandbits(4)


def rnd_wm():
    return 0xF if rng.random() < 0.6 else rng.getrandbits(4)


def blend_word(en, sc, dc, cop, sa, da, aop):
    return (en & 1) | (sc << 1) | (dc << 5) | (cop << 9) | (sa << 12) | (da << 16) | (aop << 20)


def make_beat(lanes, fmt, blend, wm, const, src, dst):
    raw, keep = M.beat(lanes, src, dst, fmt, blend, const, wm)
    cv = sum(const[c] << (32 * c) for c in range(4))
    sv = sum(src[i] << (32 * i) for i in range(16))
    dv = sum(dst[k] << (64 * k) for k in range(4))
    return "_".join([hx(lanes, 4), hx(fmt, 8), hx(blend, 24), hx(wm, 4), hx(cv, 128), hx(sv, 512),
                     hx(dv, 256), hx(raw, 256), hx(keep, 256)]), raw, keep


def rnd_beat(fmt, blend):
    flt = fmt not in M.FIXED_FMTS
    gen = rnd_src_float if flt else rnd_src_fixed
    src = [gen() for _ in range(16)]
    const = [gen() for _ in range(4)]
    dst = [rnd_dst(fmt) for _ in range(4)]
    return make_beat(rnd_lanes(), fmt, blend, rnd_wm(), const, src, dst)[0]


# ------------------------------------------------------------------ sections
def gen_ops():
    out = []
    for fmt in M.FORMATS:
        for op in range(8):
            for f in range(16):
                for slot in range(4):
                    sel = [rng.randint(0, 15) for _ in range(4)]
                    sel[slot] = f
                    en = 0 if rng.random() < 0.05 else 1
                    aop = op if slot >= 2 else rng.randint(0, 7)
                    cop = op if slot < 2 else rng.randint(0, 7)
                    out.append(rnd_beat(fmt, blend_word(en, sel[0], sel[1], cop, sel[2], sel[3], aop)))
    for fmt in [0, 37, 44, 51, 63, 65, 77, 90, 98, 109, 255]:     # unsupported formats
        for _ in range(8):
            out.append(rnd_beat(fmt, rng.getrandbits(23)))
    for _ in range(300):                                          # fully random blend words
        out.append(rnd_beat(rng.choice(M.FORMATS), rng.getrandbits(23)))
    return out


def srgb_ideal_decode(c):
    x = c / 255.0
    return x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4


def srgb_ideal_encode(v):
    v = min(max(v, 0.0), 1.0)
    x = v * 12.92 if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055
    return x * 255.0


def gen_srgb():
    out = []
    add01 = blend_word(1, 0, 1, 0, 0, 1, 0)          # 0*s + 1*d
    for fmt in M.SRGB_FMTS:
        for base in range(0, 256, 4):                # every code in every byte position, 4 lanes
            dst = []
            for k in range(4):
                c = base + k
                dst.append(c | (((c + 85) & 255) << 8) | (((c + 170) & 255) << 16) | (c << 24)
                           | (rng.getrandbits(32) << 32))
            src = [rnd_unit() for _ in range(16)]
            line, raw, keep = make_beat(0xF, fmt, add01, 0xF, [rnd_unit() for _ in range(4)], src, dst)
            for k in range(4):                       # decode + encode is the identity
                assert (raw >> (64 * k)) & 0xFFFFFFFF == dst[k] & 0xFFFFFFFF
            out.append(line)
            # MIN and MAX of s = d
            for op in (3, 4):
                src = []
                for k in range(4):
                    d = M.unpack(dst[k], fmt)
                    src += d
                line, raw, _ = make_beat(0xF, fmt, blend_word(1, 0, 0, op, 0, 0, op), 0xF,
                                         [0] * 4, src, dst)
                for k in range(4):
                    assert (raw >> (64 * k)) & 0xFFFFFFFF == dst[k] & 0xFFFFFFFF
                out.append(line)
        for c in range(256):                          # blending off: src = LUT[c] encodes to c
            src = []
            for k in range(4):
                cc = (c + 64 * k) & 255
                src += [M.SRGB_LUT[cc], M.SRGB_LUT[(cc + 1) & 255], M.SRGB_LUT[(cc + 2) & 255],
                        unorm2f(cc, 8)]
            line, raw, _ = make_beat(0xF, fmt, 0, 0xF, [0] * 4, src, [0] * 4)
            out.append(line)
    # UNORM10: every code round trips
    for base in range(0, 1024, 4):
        dst = [((base + k) | (((base + k + 341) & 1023) << 10) | (((base + k + 682) & 1023) << 20)
                | (((base + k) & 3) << 30)) for k in range(4)]
        line, raw, _ = make_beat(0xF, M.F_A2BGR10, add01, 0xF, [0] * 4, [rnd_unit() for _ in range(16)], dst)
        for k in range(4):
            assert (raw >> (64 * k)) & 0xFFFFFFFF == dst[k]
        out.append(line)
    # accuracy: decode-blend-encode (SRC_ALPHA, ONE_MINUS_SRC_ALPHA, ADD) vs float64 ideal
    worst = 0.0
    ab = blend_word(1, 6, 7, 0, 1, 7, 0)
    for _ in range(400):
        fmt = rng.choice(M.SRGB_FMTS)
        src = [rnd_unit() for _ in range(16)]
        dst = [rng.getrandbits(64) for _ in range(4)]
        line, raw, _ = make_beat(0xF, fmt, ab, 0xF, [0] * 4, src, dst)
        out.append(line)
        for k in range(4):
            d = M.unpack(dst[k], fmt)
            s = src[4 * k:4 * k + 4]
            a = b2f(s[3])
            sh = [16, 8, 0] if fmt == M.F_BGRA8_SRGB else [0, 8, 16]
            for ch in range(3):
                dc = (dst[k] >> sh[ch]) & 255
                ideal = srgb_ideal_encode(b2f(s[ch]) * a + srgb_ideal_decode(dc) * (1 - a))
                got = (raw >> (64 * k + sh[ch])) & 255
                worst = max(worst, abs(got - ideal))
    assert worst < 0.5 + 1e-3, worst            # the code is the correctly rounded ideal (within 1e-3)
    print("srgb accuracy: max |code - ideal| = %.4f (codes)" % worst)
    return out


def gen_leaf():
    # h2f exhaustive: line h -> expected fp32
    with open(os.path.join(VEC, "fblend_h2f.hex"), "w") as fh:
        for h in range(65536):
            fh.write("%08X\n" % M.h2f(h))
    # f2h: rounding boundaries + randoms
    vs = set()
    for h in range(0, 0x7C00, 1):                   # every fp16 magnitude: exact, midpoints +-1 ulp
        f = M.h2f(h)
        for s in (0, 0x80000000):
            vs.add(f | s)
            if h < 0x7BFF:
                mid = f2b(float((np.float64(b2f(f)) + np.float64(b2f(M.h2f(h + 1)))) / 2))
                for dlt in (-1, 0, 1):
                    vs.add(((mid + dlt) & 0x7FFFFFFF) | s)
    vs |= {0x477FF000, 0x477FEFFF, 0x477FF001, 0x47800000, 0x7F800000, 0xFF800000, QNAN, 0x7F800001,
           0xFFFFFFFF, 0x00000001, 0x807FFFFF, 0x33000000, 0x33000001, 0x32FFFFFF, 0x33800000}
    vs = sorted(vs)
    rng.shuffle(vs)
    vs = vs[:150000]
    while len(vs) < 260000:
        vs.append(rnd_src_float())
    with open(os.path.join(VEC, "fblend_f2h.hex"), "w") as fh:
        for f in vs:
            fh.write("%08X_%04X\n" % (f, M.f2h(f)))
    # sRGB encode: every threshold +-1 ulp, every LUT entry, specials
    se = set()
    for k in range(1, 256):
        for dlt in (-1, 0, 1):
            se.add(M.SRGB_THR[k] + dlt)
    se |= set(M.SRGB_LUT)
    se |= {0x80000000, 0xBF800000, 0x7F800000, 0xFF800000, QNAN, 0x7FFFFFFF, 0x3F800001, 0x40000000,
           0x00000001, 0x007FFFFF, 0x3F7FFFFF}
    with open(os.path.join(VEC, "fblend_senc.hex"), "w") as fh:
        for f in sorted(se):
            fh.write("%08X_%02X\n" % (f, M.srgb_encode(f)))
    print("leaf vectors: h2f 65536, f2h %d, srgb_enc %d" % (len(vs), len(se)))


def main():
    emit_rtl()
    os.makedirs(VEC, exist_ok=True)
    gen_leaf()
    ops = gen_ops()
    with open(os.path.join(VEC, "fblend_ops.hex"), "w") as fh:
        fh.write("\n".join(ops) + "\n")
    srgb = gen_srgb()
    with open(os.path.join(VEC, "fblend_srgb.hex"), "w") as fh:
        fh.write("\n".join(srgb) + "\n")
    print("beat vectors: ops %d, srgb %d" % (len(ops), len(srgb)))


if __name__ == "__main__":
    main()
